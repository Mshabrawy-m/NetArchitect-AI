"""Vendor-neutral configuration templates built from validated twin data.

The templates are design-intent text, not device-applied configuration. Every
file starts with the exact header ``TEMPLATE - not applied to any device``.
Values are copied from the digital twin's topology, addressing plan, VLAN
assignments, DHCP scopes, and modeled operational state. Nothing is fetched
from a device, and the platform never opens a management connection.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass

from digital_twin import DigitalTwin, failed_entities
from services.reporting.formatting import format_number
from simulation import twin_reference

from .common import stable_zip

TEMPLATE_HEADER = "TEMPLATE - not applied to any device"

_PLAIN_TOKEN = re.compile(r"[A-Za-z0-9_.:+/-]+")


def _token(value: object) -> str:
    """Render one value for a template line, quoting when it contains spaces."""
    text = str(value)
    if text and _PLAIN_TOKEN.fullmatch(text):
        return text
    return json.dumps(text, ensure_ascii=False)


def _number(value: float) -> str:
    return format_number(value)


def _preamble(twin: DigitalTwin, *, title: str) -> list[str]:
    reference = twin_reference(twin)
    return [
        TEMPLATE_HEADER,
        f"# {title}",
        "# Generated by NetArchitect AI from validated digital-twin data only.",
        f"# Twin: {twin.metadata.name}",
        f"# Twin fingerprint: {reference.fingerprint}",
        "",
    ]


@dataclass(frozen=True)
class ConfigTemplate:
    """One template file with a stable name and header."""

    template_id: str
    filename: str
    content: str

    def to_bytes(self) -> bytes:
        """Return the template as UTF-8 bytes."""
        return self.content.encode("utf-8")


def _device_template(twin: DigitalTwin) -> ConfigTemplate:
    down = set(failed_entities(twin).devices)
    lines = _preamble(twin, title="Device inventory")
    for device in sorted(twin.topology.devices, key=lambda item: item.id):
        lines.extend(
            [
                f"device {_token(device.id)}",
                f"  type = {_token(device.type.value)}",
                f"  role = {_token(device.role.value)}",
                f"  site = {_token(device.site)}",
                f"  modeled_state = {'down' if device.id in down else 'up'}",
                "",
            ]
        )
    return ConfigTemplate(
        template_id="devices",
        filename="devices.cfg",
        content="\n".join(lines),
    )


def _interface_template(twin: DigitalTwin) -> ConfigTemplate:
    down = set(failed_entities(twin).links)
    lines = _preamble(twin, title="Link and capacity inventory")
    for link in sorted(twin.topology.links, key=lambda item: item.id):
        first, second = link.endpoints
        lines.extend(
            [
                f"link {_token(link.id)}",
                f"  endpoint_a = {_token(first)}",
                f"  endpoint_b = {_token(second)}",
                f"  capacity_mbps = {_number(link.capacity_mbps)}",
                f"  cost = {_number(link.cost)}",
                f"  directed = {'true' if link.directed else 'false'}",
                f"  modeled_state = {'down' if link.id in down else 'up'}",
                "",
            ]
        )
    return ConfigTemplate(
        template_id="interfaces",
        filename="interfaces.cfg",
        content="\n".join(lines),
    )


def _subnet_lines(twin: DigitalTwin) -> list[str]:
    lines = _preamble(twin, title="Subnet plan")
    plan = twin.addressing
    if plan is None:
        lines.append("# No addressing plan is stored in this twin.")
        return lines
    for vlan_plan in plan.vlan_plans:
        for subnet in vlan_plan.subnets:
            lines.extend(
                [
                    f"subnet {_token(subnet.name)}",
                    f"  network = {_token(subnet.network)}",
                    f"  vlan_id = {_number(vlan_plan.vlan_id)}",
                    f"  description = {_token(subnet.description)}",
                    "",
                ]
            )
    for subnet in plan.subnets:
        lines.extend(
            [
                f"subnet {_token(subnet.name)}",
                f"  network = {_token(subnet.network)}",
                "  vlan_id = none",
                f"  description = {_token(subnet.description)}",
                "",
            ]
        )
    return lines


def _vlan_template(twin: DigitalTwin) -> ConfigTemplate:
    lines = _preamble(twin, title="VLAN assignment plan")
    plan = twin.vlan_plan
    if plan is None or not plan.assignments:
        lines.append("# No VLAN assignments are stored in this twin.")
    else:
        for assignment in plan.assignments:
            lines.extend(
                [
                    f"vlan {_number(assignment.vlan_id)}",
                    f"  name = {_token(assignment.vlan_name)}",
                    f"  department = {_token(assignment.department)}",
                    f"  subnet = {_token(assignment.subnet_name)}",
                    f"  network = {_token(assignment.network)}",
                    f"  purpose = {_token(assignment.purpose)}",
                    "",
                ]
            )
    return ConfigTemplate(
        template_id="vlans",
        filename="vlans.cfg",
        content="\n".join(lines),
    )


def _dhcp_template(twin: DigitalTwin) -> ConfigTemplate:
    lines = _preamble(twin, title="DHCP scope plan")
    if not twin.dhcp_scopes:
        lines.append("# No DHCP scopes are stored in this twin.")
    else:
        for scope in twin.dhcp_scopes:
            lines.extend(
                [
                    f"scope {_token(scope.name)}",
                    f"  network = {_token(scope.network)}",
                    "  gateway = "
                    + (_token(scope.gateway) if scope.gateway is not None else "none"),
                    "  start = "
                    + (
                        _token(scope.start_address)
                        if scope.start_address is not None
                        else "none"
                    ),
                    "  end = "
                    + (
                        _token(scope.end_address)
                        if scope.end_address is not None
                        else "none"
                    ),
                    f"  lease_minutes = {_number(scope.lease_minutes)}",
                ]
            )
            if scope.excluded_ranges:
                for start, end in scope.excluded_ranges:
                    lines.append(f"  exclude = {_token(start)} {_token(end)}")
            else:
                lines.append("  exclude = none")
            lines.append("")
    return ConfigTemplate(
        template_id="dhcp",
        filename="dhcp_scopes.cfg",
        content="\n".join(lines),
    )


def config_templates(twin: DigitalTwin) -> tuple[ConfigTemplate, ...]:
    """Return every configuration template for ``twin`` in a stable order."""
    return (
        _device_template(twin),
        _interface_template(twin),
        ConfigTemplate(
            template_id="subnets",
            filename="subnets.cfg",
            content="\n".join(_subnet_lines(twin)),
        ),
        _vlan_template(twin),
        _dhcp_template(twin),
    )


def _readme(twin: DigitalTwin) -> str:
    reference = twin_reference(twin)
    return "\n".join(
        [
            TEMPLATE_HEADER,
            "",
            "These are design-intent templates generated from validated",
            "digital-twin data. They are not applied to any device, are not",
            "vendor-complete, and are not validated by a device.",
            "",
            f"Twin: {twin.metadata.name}",
            f"Twin fingerprint: {reference.fingerprint}",
            "",
            "Files:",
            "- devices.cfg: device ids, types, roles, sites, modeled state",
            "- interfaces.cfg: link endpoints, capacity, cost, modeled state",
            "- subnets.cfg: stored subnet plan",
            "- vlans.cfg: stored VLAN assignments",
            "- dhcp_scopes.cfg: stored DHCP scopes",
            "",
            "An absent operational-state entry is modeled as up by the twin.",
            "",
        ]
    )


def to_config_bundle(twin: DigitalTwin) -> bytes:
    """Build an in-memory ZIP of configuration templates and a README."""
    files = [(template.filename, template.to_bytes()) for template in config_templates(twin)]
    files.append(("README.txt", _readme(twin).encode("utf-8")))
    return stable_zip(files, kind="configuration template bundle")


