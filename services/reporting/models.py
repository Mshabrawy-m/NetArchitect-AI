"""Typed, provenance-tagged report document (Phase 11a).

A :class:`ReportDocument` is the stable intermediate representation shared by
the UI and every exporter. It contains only values copied from validated
application data, and every number carries the workflow step, tool, and twin
fingerprint that produced it.

Content is an ordered list of sections. Each section holds typed blocks:
paragraphs, key/value lists, tables, and notes. A section that could not be
produced is kept with ``status="not_run"`` plus the reason and the page that
produces the missing data; the report never invents a value to fill a gap.

All models are pure data. They import nothing from Streamlit or ReportLab.
"""

from __future__ import annotations

from datetime import datetime
from enum import Enum
from typing import Annotated, Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator

REPORT_SCHEMA_VERSION: int = 1

# The exact disclosure line used by every export. The PDF footer uses this
# string verbatim so it can be located in the generated byte stream.
DISCLOSURE_TEXT = (
    "Software model; modeled estimates; not packet-level or hardware-accurate."
)

MODELED_ESTIMATE_LABEL = (
    "Modeled estimate: derived from stated assumptions, not measured on live "
    "equipment."
)
TEMPLATE_LABEL = "Template, not device-applied."
SAMPLE_DATA_LABEL = "Sample or example data is labelled; it is not production data."

# Every report carries these labels. They are enforced by the consistency
# checker instead of being trusted to each call site.
REQUIRED_LABELS: tuple[str, ...] = (
    DISCLOSURE_TEXT,
    MODELED_ESTIMATE_LABEL,
    TEMPLATE_LABEL,
    SAMPLE_DATA_LABEL,
)


class BlockKind(str, Enum):
    """Kinds of content block a report section may contain."""

    paragraph = "paragraph"
    key_value = "key_value"
    table = "table"
    note = "note"


class SectionStatus(str, Enum):
    """Whether a section was produced from available data."""

    available = "available"
    not_run = "not_run"


class Provenance(BaseModel):
    """Where one value or table came from."""

    model_config = ConfigDict(extra="forbid")

    step: str = Field(min_length=1, description="Workflow step or engine area.")
    tool: str = Field(min_length=1, description="Function or model that produced it.")
    twin_version: str = Field(
        default="",
        description="SHA-256 fingerprint of the twin revision the value came from.",
    )


class ValueRecord(BaseModel):
    """One sourced number or text fact, kept as the report's audit appendix."""

    model_config = ConfigDict(extra="forbid")

    key: str = Field(
        min_length=1,
        description="Stable identifier unique within one report.",
    )
    label: str = Field(min_length=1, description="Human-readable description.")
    display: str = Field(description="Value exactly as printed in the document.")
    numeric: float | None = Field(
        default=None,
        description="Parsed numeric value, or None for a non-numeric fact.",
    )
    unit: str = Field(default="", description="Unit printed next to the value.")
    provenance: Provenance


class ReportTwin(BaseModel):
    """Reference to the twin revision the report describes."""

    model_config = ConfigDict(extra="forbid")

    name: str = Field(min_length=1)
    created_at: datetime
    schema_version: int = Field(ge=1)
    fingerprint: str = Field(
        min_length=1,
        description="SHA-256 of the twin's canonical JSON serialization.",
    )


class ParagraphBlock(BaseModel):
    """Deterministic prose whose numbers are listed in ``ValueRecord``."""

    model_config = ConfigDict(extra="forbid")

    kind: Literal["paragraph"] = "paragraph"
    text: str = Field(min_length=1)
    provenance: Provenance | None = None


class KeyValueItem(BaseModel):
    """One labelled value with its provenance."""

    model_config = ConfigDict(extra="forbid")

    key: str = Field(min_length=1)
    value: str = Field(min_length=1)
    unit: str = ""
    provenance: Provenance


class KeyValueBlock(BaseModel):
    """A labelled list of values, such as the twin reference summary."""

    model_config = ConfigDict(extra="forbid")

    kind: Literal["key_value"] = "key_value"
    title: str = ""
    items: tuple[KeyValueItem, ...] = Field(default_factory=tuple)


class TableBlock(BaseModel):
    """A bounded table whose numbers share one provenance record.

    ``total_rows`` records how many rows the source produced. When it exceeds
    ``len(rows)`` the exporters add a visible "showing first N of M" note.
    """

    model_config = ConfigDict(extra="forbid")

    kind: Literal["table"] = "table"
    id: str = Field(min_length=1, description="Stable id used for CSV file names.")
    title: str
    columns: tuple[str, ...] = Field(min_length=1)
    rows: tuple[tuple[str, ...], ...] = Field(default_factory=tuple)
    total_rows: int = Field(default=0, ge=0)
    provenance: Provenance

    @model_validator(mode="after")
    def _validate_shape(self) -> TableBlock:
        for row in self.rows:
            if len(row) != len(self.columns):
                raise ValueError(
                    f"Table {self.id!r} row has {len(row)} cells but "
                    f"{len(self.columns)} columns are declared"
                )
        if self.total_rows < len(self.rows):
            raise ValueError(
                f"Table {self.id!r} reports {self.total_rows} total rows but "
                f"contains {len(self.rows)}"
            )
        return self

    @property
    def shown_rows(self) -> int:
        """Return how many rows this document retains."""
        return len(self.rows)

    @property
    def truncated(self) -> bool:
        """Return whether source rows were omitted."""
        return self.total_rows > len(self.rows)

    def truncation_note(self) -> str:
        """Return the visible truncation note, or an empty string."""
        if not self.truncated:
            return ""
        return f"Showing first {self.shown_rows} of {self.total_rows} rows."


class NoteBlock(BaseModel):
    """A deterministic note, warning, or limitation."""

    model_config = ConfigDict(extra="forbid")

    kind: Literal["note"] = "note"
    text: str = Field(min_length=1)
    severity: Literal["info", "warning", "limitation"] = "info"
    provenance: Provenance | None = None


ContentBlock = Annotated[
    ParagraphBlock | KeyValueBlock | TableBlock | NoteBlock,
    Field(discriminator="kind"),
]


class ReportSection(BaseModel):
    """One ordered report section, available or explicitly not run."""

    model_config = ConfigDict(extra="forbid")

    id: str = Field(min_length=1)
    title: str = Field(min_length=1)
    status: SectionStatus = SectionStatus.available
    blocks: tuple[ContentBlock, ...] = Field(default_factory=tuple)
    unavailable_reason: str = ""
    producer_page: str = Field(
        default="",
        description="Page that produces the missing data, for a not-run section.",
    )

    @model_validator(mode="after")
    def _validate_status(self) -> ReportSection:
        if self.status is SectionStatus.not_run:
            if not self.unavailable_reason:
                raise ValueError(
                    f"Section {self.id!r} is not run but has no reason"
                )
            if not self.producer_page:
                raise ValueError(
                    f"Section {self.id!r} is not run but names no producing page"
                )
        return self


class AIExplanation(BaseModel):
    """Optional model-written prose, always labelled and never authoritative."""

    model_config = ConfigDict(extra="forbid")

    text: str = ""
    label: str = "AI-generated text; not a source of design data."
    provider_used: bool = False
    rejected: bool = False
    note: str = ""


class ReportDocument(BaseModel):
    """One complete, ordered, provenance-tagged report."""

    model_config = ConfigDict(extra="forbid")

    schema_version: int = REPORT_SCHEMA_VERSION
    title: str = Field(min_length=1)
    subtitle: str = ""
    generated_at: datetime
    twin: ReportTwin
    sections: tuple[ReportSection, ...]
    values: tuple[ValueRecord, ...] = Field(default_factory=tuple)
    labels: tuple[str, ...] = REQUIRED_LABELS
    ai: AIExplanation | None = None
    model_note: str = DISCLOSURE_TEXT

    @model_validator(mode="after")
    def _validate_document(self) -> ReportDocument:
        section_ids: set[str] = set()
        for section in self.sections:
            if section.id in section_ids:
                raise ValueError(f"Duplicate report section id: {section.id!r}")
            section_ids.add(section.id)
        value_keys: set[str] = set()
        for value in self.values:
            if value.key in value_keys:
                raise ValueError(f"Duplicate report value key: {value.key!r}")
            value_keys.add(value.key)
        if not self.labels:
            raise ValueError("A report must carry its disclosure labels")
        return self

    def section(self, section_id: str) -> ReportSection | None:
        """Return one section by id, or None when it is absent."""
        for section in self.sections:
            if section.id == section_id:
                return section
        return None

    def section_ids(self) -> tuple[str, ...]:
        """Return section ids in document order."""
        return tuple(section.id for section in self.sections)

    def available_section_ids(self) -> tuple[str, ...]:
        """Return ids of sections that contain produced data."""
        return tuple(
            section.id
            for section in self.sections
            if section.status is SectionStatus.available
        )

    def tables(self) -> tuple[TableBlock, ...]:
        """Return every table block in document order."""
        return tuple(
            block
            for section in self.sections
            for block in section.blocks
            if isinstance(block, TableBlock)
        )


